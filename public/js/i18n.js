export function getSavedLanguage() {
  try {
    const saved = localStorage.getItem('ygo_md_lang');
    return saved === 'th' ? 'th' : 'en';
  } catch {
    return 'en';
  }
}

export function saveLanguage(lang) {
  try {
    localStorage.setItem('ygo_md_lang', lang);
  } catch {
    // Ignore storage restriction
  }
}

export function t(lang, key) {
  return I18N_STRINGS[lang]?.[key] || I18N_STRINGS.en[key] || I18N_STRINGS.th[key] || key;
}

export function getLocalizedCardName(card, lang) {
  if (!card) return '';
  return lang === 'en' ? (card.name || card.nameTh) : (card.nameTh || card.name);
}

export function getLocalizedCardDesc(card, lang) {
  if (!card) return '';
  return lang === 'en' ? (card.description || card.descriptionTh) : (card.descriptionTh || card.description);
}
